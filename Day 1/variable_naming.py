## Variable naming rules:
# 1. Can contain letters, numbers, and underscores.
# 2. Cannot start with a number.
# 3. Cannot contain spaces.
# 4. Cannot use special characters like @, -, or .
# 5. Cannot be a Python keyword such as if, for, or class.
# 6. Variable names are case-sensitive.
# 7. Use snake_case for readable variable names.
user_name = "ayush"#valid user name
# user name = "ayush"#invalid user name because it contains a space
# user-name = "ayush"#invalid user name because it contains a special character
username = "ayush"#valid user name
username1 = "ayush"#valid user name
# username@ = "ayush"#invalid user name because it contains a special character
